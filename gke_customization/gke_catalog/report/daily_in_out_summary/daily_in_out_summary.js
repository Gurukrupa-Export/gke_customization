frappe.query_reports["Daily In Out Summary"] = {
	"filters": [
		{
			"fieldname": "company",
			"label": __("Company"),
			"fieldtype": "Link",
			"options": "Company",
			"default": frappe.defaults.get_user_default("Company")
		},
		{
			"fieldname": "from_date",
			"label": __("From Date"),
			"fieldtype": "Date",
			"default": frappe.datetime.month_start()
		},
		{
			"fieldname": "to_date",
			"label": __("To Date"),
			"fieldtype": "Date",
			"default": frappe.datetime.get_today()
		}
	],
	"onload": function (report) {
		report.page.add_inner_button(__("Summary"), function () {
			show_summary_dialog(report);
		});
	}
};

function show_summary_dialog(report) {
	const company = report.get_filter_value("company");

	frappe.call({
		method:
			"gke_customization.gke_catalog.report.daily_in_out_summary.daily_in_out_summary.get_summary",
		args: { company: company },
		callback: function (r) {
			if (!r.message) return;
			render_summary_dialog(r.message, company);
		}
	});
}

const DETAIL_KEYS = ["inward_qty", "return_qty", "supply_qty", "sales_return_qty"];

function open_detail_list(col, row, company, dialog) {
	frappe.call({
		method:
			"gke_customization.gke_catalog.report.daily_in_out_summary.daily_in_out_summary.get_detail_vouchers",
		args: { company: company, from_date: row.from_date, to_date: row.to_date, key: col },
		callback: function (r) {
			if (!r.message) return;
			const { doctype, names } = r.message;

			if (!names || !names.length) {
				frappe.msgprint(__("No records found for this figure."));
				return;
			}

			dialog.hide();
			frappe.set_route("List", doctype, { name: ["in", names] });
		}
	});
}

const SUMMARY_SECTIONS = [
	{ key: "today", title: __("Today") },
	{ key: "current_month", title: __("Current Month") },
	{ key: "previous_month", title: __("Previous Month") },
	{ key: "current_fy", title: __("Current Financial Year") }
];

const SUMMARY_COLUMNS = [
	{ label: __("Opening Stock"), key: "opening_stock" },
	{ label: __("Inward Qty"), key: "inward_qty" },
	{ label: __("Return Qty"), key: "return_qty" },
	{ label: __("Total Stock"), key: "total_stock" },
	{ label: __("Supply (Sold)"), key: "supply_qty" },
	{ label: __("Sales Return"), key: "sales_return_qty" },
	{ label: __("Closing Stock"), key: "closing_stock" }
];

const DIAMOND_GLYPH = `
	<svg width="13" height="13" viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg">
		<path d="M4 9L12 3L20 9L12 21L4 9Z" stroke="currentColor" stroke-width="1.4" stroke-linejoin="round"/>
		<path d="M4 9H20M8.5 9L12 3L15.5 9M8.5 9L12 21M15.5 9L12 21" stroke="currentColor" stroke-width="0.9" opacity="0.6"/>
	</svg>`;

function period_label(section, row) {
	return section.key === "today"
		? frappe.datetime.str_to_user(row.from_date)
		: `${frappe.datetime.str_to_user(row.from_date)} – ${frappe.datetime.str_to_user(row.to_date)}`;
}

function render_summary_dialog(summary, company) {
	const generated_on = frappe.datetime.str_to_user(frappe.datetime.get_today());

	let rows = "";
	SUMMARY_SECTIONS.forEach((section) => {
		const row = summary[section.key] || {};

		rows += `
			<tr>
				<td class="sadguru-col-period">
					<div class="sadguru-period-title">${section.title}</div>
					<div class="sadguru-period-range">${period_label(section, row)}</div>
				</td>
				${SUMMARY_COLUMNS.map((c) => {
					const cls = c.key === "closing_stock" ? "sadguru-closing" : c.key === "total_stock" ? "sadguru-subtotal" : "";
					const value = flt_fmt(row[c.key]);
					const inner = DETAIL_KEYS.includes(c.key)
						? `<span class="sadguru-value-link" data-section="${section.key}" data-col="${c.key}">${value}</span>`
						: value;
					return `<td class="${cls}">${inner}</td>`;
				}).join("")}
			</tr>`;
	});

	const html = `
		<div class="sadguru-summary">
			<div class="sadguru-report-head">
				<div class="sadguru-brand">${DIAMOND_GLYPH}<span>${__("Stock Statement")}</span></div>
				<div class="sadguru-report-meta">
					<div>${__("As on")} <b>${generated_on}</b></div>
					<div class="sadguru-report-sub">${__("Quantities in Carats (Crt)")}</div>
				</div>
			</div>
			<div class="sadguru-accent-bar"></div>
			<div class="sadguru-table-wrap">
				<table class="sadguru-table">
					<thead>
						<tr>
							<th class="sadguru-col-period">${__("Period")}</th>
							${SUMMARY_COLUMNS.map((c) => `<th>${c.label}</th>`).join("")}
						</tr>
					</thead>
					<tbody>${rows}</tbody>
				</table>
			</div>
			<div class="sadguru-footer">${__("Generated by")} ${frappe.session.user_fullname || frappe.session.user}</div>
		</div>`;

	const dialog = new frappe.ui.Dialog({
		title: __("Sadguru In/Out Stock Summary"),
		size: "extra-large",
		fields: [
			{
				fieldtype: "HTML",
				fieldname: "summary_html",
				options: html
			}
		],
		primary_action_label: __("Export as PDF"),
		primary_action: function () {
			export_summary_pdf(summary, generated_on);
		}
	});

	if (!document.getElementById("sadguru-summary-style")) {
		const style = document.createElement("style");
		style.id = "sadguru-summary-style";
		style.innerHTML = SADGURU_SUMMARY_CSS;
		document.head.appendChild(style);
	}

	dialog.show();

	dialog.$wrapper.find(".sadguru-value-link").on("click", function () {
		const section_key = $(this).data("section");
		const col = $(this).data("col");
		const row = summary[section_key];
		if (!row) return;

		open_detail_list(col, row, company, dialog);
	});
}

